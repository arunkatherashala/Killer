//
// Image generation:
//   kala_generate_image(prompt)                  → image rendered in chat (Pollinations free by default)
//   kala_generate_image(prompt, style)            → style: "photorealistic"|"artistic"|"anime"|"3d"|"sketch"
//   kala_generate_image(prompt, style, size)      → size: "square"|"landscape"|"portrait"|"hd"
