pub fn generate_video(prompt: &str, duration: &str) -> String {
    let cinematic = enhance_video_prompt(prompt);
    let (provider, api_key, _model) = get_gen_config();

    match provider.to_lowercase().as_str() {
        "runway" if !api_key.is_empty() =>
            generate_video_runway(&cinematic, &api_key, duration)
                .unwrap_or_else(|_| generate_video_native_wrapped(prompt)),
        _ => generate_video_native_wrapped(prompt),
    }
}

