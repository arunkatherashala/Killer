fn curl_post(url: &str, headers: &[String], body: &str, timeout_s: u64) -> Result<String, String> {
    if !url.starts_with("https://") {
        return Err(format!("URL must use HTTPS: {}", &url[..url.len().min(50)]));
    }
    let timeout_str = timeout_s.to_string();
    let mut args = vec!["-s", "--fail-with-body", "--max-time", &timeout_str, "-X", "POST", url];
    let header_args: Vec<String> = headers.iter()
        .flat_map(|h| vec!["-H".to_string(), h.clone()])
        .collect();
    let header_refs: Vec<&str> = header_args.iter().map(|s| s.as_str()).collect();
    args.extend_from_slice(&header_refs);
    args.extend_from_slice(&["-d", body]);

    let output = Command::new("curl").args(&args).output()
        .map_err(|e| format!("curl not found: {}", e))?;
    let stdout = String::from_utf8_lossy(&output.stdout).to_string();
    let stderr = String::from_utf8_lossy(&output.stderr).to_string();
    if stdout.is_empty() && !stderr.is_empty() {
        return Err(format!("curl: {}", stderr.trim()));
    }
    Ok(stdout)
}

fn json_escape(s: &str) -> String {
    format!("\"{}\"", s
        .replace('\\', "\\\\").replace('"', "\\\"")
        .replace('\n', "\\n").replace('\r', "\\r").replace('\t', "\\t"))
}

fn extract_json_str(json: &str, key: &str) -> Option<String> {
    let needle = format!("\"{}\":", key);
    let pos = json.find(&needle)?;
    let rest = json[pos + needle.len()..].trim_start();
    if !rest.starts_with('"') { return None; }
    let inner = &rest[1..];
    let mut result = String::new();
    let mut chars = inner.chars().peekable();
    loop {
        match chars.next()? {
            '\\' => match chars.next()? {
                '"'  => result.push('"'), '\\' => result.push('\\'),
                'n'  => result.push('\n'), 'r' => result.push('\r'),
                't'  => result.push('\t'), c   => { result.push('\\'); result.push(c); }
            },
            '"' => break,
            c   => result.push(c),
        }
    }
    Some(result)
}

fn base64_decode_to_bytes(s: &str) -> Result<Vec<u8>, ()> {
    const T: &[u8; 64] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    let mut rev = [255u8; 256];
    for (i, &c) in T.iter().enumerate() { rev[c as usize] = i as u8; }

    let bytes: Vec<u8> = s.bytes().filter(|&b| b != b'=' && b != b'\n' && b != b'\r').collect();
    let mut out = Vec::with_capacity(bytes.len() * 3 / 4);
    let mut i = 0;
    while i + 3 < bytes.len() {
        let [a, b, c, d] = [rev[bytes[i] as usize], rev[bytes[i+1] as usize],
                            rev[bytes[i+2] as usize], rev[bytes[i+3] as usize]];
        if a == 255 || b == 255 { break; }
        out.push((a << 2) | (b >> 4));
        if c != 255 { out.push((b << 4) | (c >> 2)); }
        if d != 255 { out.push((c << 6) | d); }
        i += 4;
    }
    Ok(out)
}

fn get_str_arg(args: &[Value], idx: usize, name: &str) -> Result<String, VmError> {
    match args.get(idx) {
        Some(Value::Str(s)) => Ok(s.clone()),
        Some(_) => Err(VmError::runtime_error(format!("argument '{}' must be a string", name))),
        None    => Err(VmError::runtime_error(format!("missing argument '{}'", name))),
    }
}
