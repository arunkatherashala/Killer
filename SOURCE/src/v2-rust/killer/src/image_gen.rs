#[allow(dead_code)]
fn url_encode_prompt(s: &str) -> String {
    let mut out = String::with_capacity(s.len() * 2);
    for c in s.chars() {
        match c {
            'a'..='z' | 'A'..='Z' | '0'..='9' | '-' | '_' | '.' => out.push(c),
            ' ' => out.push('+'),
            _ => for b in c.to_string().bytes() { out.push_str(&format!("%{:02X}", b)); },
        }
    }
    out
}

