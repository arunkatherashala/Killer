pub fn generate_image(prompt: &str, style: &str, size: &str) -> String {
    let (provider, api_key, _model) = get_gen_config();

    // Use configured premium provider if available
    if provider.to_lowercase() == "openai" && !api_key.is_empty() {
        let enhanced = enhance_image_prompt(prompt, style);
        return generate_image_dalle(&enhanced, &api_key, size)
            .unwrap_or_else(|_| generate_image_native_wrapped(prompt, style));
    }
    if provider.to_lowercase() == "stability" && !api_key.is_empty() {
        let enhanced = enhance_image_prompt(prompt, style);
        return generate_image_stability(&enhanced, &api_key, size)
            .unwrap_or_else(|_| generate_image_native_wrapped(prompt, style));
    }

    // Default: Nova Native — pure Rust procedural image synthesis
    // Zero network, zero API keys, instant generation < 10ms
    generate_image_native_wrapped(prompt, style)
}

