pub fn get_gen_config() -> (String, String, String) {
    // Dedicated env vars take priority
    let runway_key    = std::env::var("RUNWAY_API_KEY").unwrap_or_default();
    let stability_key = std::env::var("STABILITY_API_KEY").unwrap_or_default();
    let openai_key    = std::env::var("OPENAI_API_KEY").unwrap_or_default();

    if !runway_key.is_empty()    { return ("runway".into(),    runway_key,    String::new()); }
    if !stability_key.is_empty() { return ("stability".into(), stability_key, String::new()); }
    if !openai_key.is_empty()    { return ("openai".into(),    openai_key,    "dall-e-3".into()); }

    // Fall back to khlm_polyglot config (set via kala_set_llm)
    let cfg = config().lock().unwrap();
    (cfg.llm_provider.clone(), cfg.llm_api_key.clone(), cfg.llm_model.clone())
}

