/// kala_generate_image(prompt [, style [, size]]) → String
///
/// Generates an image from a text description.
///
/// Arguments:
///   prompt  — what to generate, e.g. "a sunset over Tokyo in neon lights"
///   style   — "photorealistic" | "artistic" | "anime" | "3d" | "sketch" | "cinematic" | "auto"
///   size    — "square" | "landscape" | "portrait" | "hd"
///
/// Killer:
///   url = kala_generate_image("a city skyline built on glowing Killer code circuits")
///   print(K"Image: {url}")
pub fn builtin_kala_generate_image(args: &[Value]) -> Result<Value, VmError> {
    crate::security::require_llm()?;
    crate::security::require_network()?;
    let prompt = get_str_arg(args, 0, "prompt")?;
    let style  = get_str_arg(args, 1, "style").unwrap_or_else(|_| "auto".into());
    let size   = get_str_arg(args, 2, "size").unwrap_or_else(|_| "square".into());
    Ok(Value::Str(generate_image(&prompt, &style, &size)))
}

/// kala_generate_video(prompt [, duration]) → String
///
/// Generates a short video clip from a text description.
///
/// Arguments:
///   prompt   — scene description
///   duration — "5" or "10" (seconds)
///
/// Killer:
///   result = kala_generate_video("a neon Killer code city at dawn, drone shot", "5")
///   print(result)
pub fn builtin_kala_generate_video(args: &[Value]) -> Result<Value, VmError> {
    crate::security::require_llm()?;
    crate::security::require_network()?;
    let prompt   = get_str_arg(args, 0, "prompt")?;
    let duration = get_str_arg(args, 1, "duration").unwrap_or_else(|_| "5".into());
    Ok(Value::Str(generate_video(&prompt, &duration)))
}

