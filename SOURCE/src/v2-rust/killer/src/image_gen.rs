// ─────────────────────────────────────────────────────────────────────────────
// PROMPT ENHANCEMENT
// ─────────────────────────────────────────────────────────────────────────────

pub fn enhance_image_prompt(prompt: &str, style: &str) -> String {
    let suffix = match style.to_lowercase().as_str() {
        "photorealistic" | "photo" | "realistic" =>
            ", photorealistic, 8K UHD, professional photography, sharp focus, natural lighting",
        "artistic" | "art" | "painting" =>
            ", digital painting, concept art, highly detailed, vibrant colors, artstation trending",
        "anime" =>
            ", anime style, studio ghibli inspired, smooth lines, vibrant colors, detailed background",
        "3d" | "render" =>
            ", 3D render, octane render, ray tracing, volumetric lighting, ultra-detailed",
        "sketch" | "drawing" =>
            ", pencil sketch, clean linework, professional illustration, detailed shading",
        "cinematic" =>
            ", cinematic lighting, movie still, anamorphic lens, dramatic atmosphere, award-winning",
        _ => {
            let p = prompt.to_lowercase();
            if p.contains("killer") || p.contains("code") || p.contains("circuit") {
                ", cyberpunk aesthetic, neon glowing circuits, dark background, ultra-detailed, 8K"
            } else if p.contains("portrait") || p.contains("person") || p.contains("face") {
                ", professional portrait, studio lighting, sharp focus, photorealistic, 8K"
            } else if p.contains("city") || p.contains("skyline") || p.contains("architecture") {
                ", architectural photography, dramatic lighting, 8K, sharp detail"
            } else if p.contains("nature") || p.contains("landscape") || p.contains("forest") {
                ", landscape photography, golden hour, 8K, HDR, National Geographic style"
            } else if p.contains("space") || p.contains("galaxy") || p.contains("nebula") {
                ", NASA photo quality, deep space, vibrant nebula colors, ultra-detailed, 8K"
            } else {
                ", highly detailed, professional quality, vibrant, sharp focus, 8K"
            }
        }
    };
    format!("{}{}", prompt, suffix)
}

pub fn enhance_video_prompt(prompt: &str) -> String {
    let p = prompt.to_lowercase();
    let camera = if p.contains("city") || p.contains("skyline") {
        "cinematic drone shot, slow aerial pan"
    } else if p.contains("person") || p.contains("character") || p.contains("human") {
        "medium shot, cinematic depth of field"
    } else if p.contains("nature") || p.contains("landscape") {
        "sweeping landscape shot, slow motion"
    } else {
        "smooth camera movement, cinematic"
    };

    format!("{}, {}, high quality, detailed, professional cinematography, smooth motion, 24fps",
        prompt, camera)
}

