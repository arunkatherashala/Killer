// ── Triangle fill (for arrows, icons) ───────────────────────────────────────

impl Framebuffer {
    /// Fill a triangle defined by three points.
    pub fn fill_triangle(&mut self, x0: i32, y0: i32, x1: i32, y1: i32, x2: i32, y2: i32, color: Color) {
        let min_y = y0.min(y1).min(y2).max(0);
        let max_y = y0.max(y1).max(y2).min(self.height as i32 - 1);
        for y in min_y..=max_y {
            let mut min_x = self.width as i32;
            let mut max_x = 0i32;
            for &(ax, ay, bx, by) in &[(x0,y0,x1,y1),(x1,y1,x2,y2),(x2,y2,x0,y0)] {
                if (ay <= y && by > y) || (by <= y && ay > y) {
                    let t = (y - ay) as f64 / (by - ay) as f64;
                    let ix = ax + (t * (bx - ax) as f64) as i32;
                    min_x = min_x.min(ix);
                    max_x = max_x.max(ix);
                }
            }
            for x in min_x.max(0)..=max_x.min(self.width as i32 - 1) {
                self.set_pixel(x, y, color);
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn new_framebuffer_is_black() {
        let fb = Framebuffer::new(10, 10);
        assert_eq!(fb.pixels.len(), 400);
        assert!(fb.pixels.iter().all(|&b| b == 0));
    }

    #[test]
    fn clear_fills_all_pixels() {
        let mut fb = Framebuffer::new(4, 4);
        fb.clear(Color::WHITE);
        for chunk in fb.pixels.chunks_exact(4) {
            assert_eq!(chunk, &[255, 255, 255, 255]);
        }
    }

    #[test]
    fn fill_rect_clipped() {
        let mut fb = Framebuffer::new(10, 10);
        fb.fill_rect(-5, -5, 20, 20, Color::RED);
        let idx = 0usize; // pixel (0,0)
        assert_eq!(fb.pixels[idx], 220); // R
    }

    #[test]
    fn draw_text_advances() {
        let mut fb = Framebuffer::new(200, 20);
        let adv = fb.draw_text("Hi", 0, 0, Color::WHITE, 1);
        assert!(adv > 0);
    }

    #[test]
    fn measure_text_matches_draw() {
        let measured = Framebuffer::measure_text("Hello", 1);
        let mut fb = Framebuffer::new(200, 20);
        let drawn = fb.draw_text("Hello", 0, 0, Color::WHITE, 1);
        assert_eq!(measured, drawn);
    }

    #[test]
    fn bgr_output_correct_size() {
        let fb = Framebuffer::new(10, 10);
        let bgr = fb.to_bgr_bottom_up();
        let stride = ((10 * 3 + 3) / 4 * 4) as usize;
        assert_eq!(bgr.len(), stride * 10);
    }
}
