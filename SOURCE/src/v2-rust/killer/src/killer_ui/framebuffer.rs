const FONT_W: u8 = 6;
const FONT_H: u8 = 10;

/// Returns 10-byte glyph bitmap for char `ch`. Each byte = 1 row, MSB-first, 6 bits wide.
fn font_glyph(ch: char) -> [u8; 10] {
    let idx = ch as u32;
    if idx < 32 || idx > 126 {
        return FONT_DATA[0]; // space fallback
    }
    FONT_DATA[(idx - 32) as usize]
}

