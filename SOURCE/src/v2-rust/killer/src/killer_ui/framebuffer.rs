//! **Software framebuffer** — draw primitives (rect, text, line, circle) to an RGBA pixel buffer.
//!
//! Zero dependencies. Widgets render to this buffer, then it is blitted to a Win32 window.

use super::style::Color;

/// RGBA framebuffer: row-major, 4 bytes per pixel (R, G, B, A).
pub struct Framebuffer {
    pub width: u32,
    pub height: u32,
    pub pixels: Vec<u8>,
}

impl Framebuffer {
    pub fn new(width: u32, height: u32) -> Self {
        Self {
            width,
            height,
            pixels: vec![0; (width * height * 4) as usize],
        }
    }

    #[inline]
    pub fn clear(&mut self, color: Color) {
        for chunk in self.pixels.chunks_exact_mut(4) {
            chunk[0] = color.r;
            chunk[1] = color.g;
            chunk[2] = color.b;
            chunk[3] = color.a;
        }
    }

    #[inline(always)]
    fn set_pixel(&mut self, x: i32, y: i32, color: Color) {
        if x < 0 || y < 0 || x >= self.width as i32 || y >= self.height as i32 {
            return;
        }
        let idx = ((y as u32 * self.width + x as u32) * 4) as usize;
        if color.a == 255 {
            self.pixels[idx]     = color.r;
            self.pixels[idx + 1] = color.g;
            self.pixels[idx + 2] = color.b;
            self.pixels[idx + 3] = 255;
        } else if color.a > 0 {
            let a = color.a as u16;
            let inv = 255 - a;
            self.pixels[idx]     = ((color.r as u16 * a + self.pixels[idx]     as u16 * inv) / 255) as u8;
            self.pixels[idx + 1] = ((color.g as u16 * a + self.pixels[idx + 1] as u16 * inv) / 255) as u8;
            self.pixels[idx + 2] = ((color.b as u16 * a + self.pixels[idx + 2] as u16 * inv) / 255) as u8;
            self.pixels[idx + 3] = 255;
        }
    }

    /// Fill a solid rectangle (clipped).
    pub fn fill_rect(&mut self, x: i32, y: i32, w: u32, h: u32, color: Color) {
        let x0 = x.max(0);
        let y0 = y.max(0);
        let x1 = (x + w as i32).min(self.width as i32);
        let y1 = (y + h as i32).min(self.height as i32);
        for py in y0..y1 {
            for px in x0..x1 {
                self.set_pixel(px, py, color);
            }
        }
    }

    /// Draw a 1px border rectangle.
    pub fn stroke_rect(&mut self, x: i32, y: i32, w: u32, h: u32, color: Color) {
        let w = w as i32;
        let h = h as i32;
        // top & bottom
        for px in x..x + w {
            self.set_pixel(px, y, color);
            self.set_pixel(px, y + h - 1, color);
        }
        // left & right
        for py in y..y + h {
            self.set_pixel(x, py, color);
            self.set_pixel(x + w - 1, py, color);
        }
    }

    /// Draw a rounded rectangle (fill) with radius `r`.
    pub fn fill_rounded_rect(&mut self, x: i32, y: i32, w: u32, h: u32, r: u32, color: Color) {
        let r = r.min(w / 2).min(h / 2);
        let wi = w as i32;
        let hi = h as i32;
        let ri = r as i32;
        // Fill center cross (no rounding needed)
        self.fill_rect(x + ri, y, w - 2 * r, h, color);
        self.fill_rect(x, y + ri, w, h - 2 * r, color);
        // Fill corners via circle distance check
        let r2 = (ri * ri) as f64;
        for qy in 0..ri {
            for qx in 0..ri {
                let dx = ri - 1 - qx;
                let dy = ri - 1 - qy;
                if (dx as f64 + 0.5).powi(2) + (dy as f64 + 0.5).powi(2) <= r2 + ri as f64 {
                    // top-left
                    self.set_pixel(x + qx, y + qy, color);
                    // top-right
                    self.set_pixel(x + wi - 1 - qx, y + qy, color);
                    // bottom-left
                    self.set_pixel(x + qx, y + hi - 1 - qy, color);
                    // bottom-right
                    self.set_pixel(x + wi - 1 - qx, y + hi - 1 - qy, color);
                }
            }
        }
    }

    /// Horizontal line.
    pub fn hline(&mut self, x: i32, y: i32, len: u32, color: Color) {
        for px in x..x + len as i32 {
            self.set_pixel(px, y, color);
        }
    }

    /// Vertical line.
    pub fn vline(&mut self, x: i32, y: i32, len: u32, color: Color) {
        for py in y..y + len as i32 {
            self.set_pixel(x, py, color);
        }
    }

    /// Bresenham line.
    pub fn line(&mut self, mut x0: i32, mut y0: i32, x1: i32, y1: i32, color: Color) {
        let dx = (x1 - x0).abs();
        let dy = -(y1 - y0).abs();
        let sx = if x0 < x1 { 1 } else { -1 };
        let sy = if y0 < y1 { 1 } else { -1 };
        let mut err = dx + dy;
        loop {
            self.set_pixel(x0, y0, color);
            if x0 == x1 && y0 == y1 { break; }
            let e2 = 2 * err;
            if e2 >= dy { err += dy; x0 += sx; }
            if e2 <= dx { err += dx; y0 += sy; }
        }
    }

    /// Fill circle (midpoint algorithm).
    pub fn fill_circle(&mut self, cx: i32, cy: i32, radius: u32, color: Color) {
        let r = radius as i32;
        for dy in -r..=r {
            let half_w = ((r * r - dy * dy) as f64).sqrt() as i32;
            for dx in -half_w..=half_w {
                self.set_pixel(cx + dx, cy + dy, color);
            }
        }
    }

    /// Stroke circle (1px).
    pub fn stroke_circle(&mut self, cx: i32, cy: i32, radius: u32, color: Color) {
        let mut x = radius as i32;
        let mut y: i32 = 0;
        let mut err = 1 - x;
        while x >= y {
            self.set_pixel(cx + x, cy + y, color);
            self.set_pixel(cx - x, cy + y, color);
            self.set_pixel(cx + x, cy - y, color);
            self.set_pixel(cx - x, cy - y, color);
            self.set_pixel(cx + y, cy + x, color);
            self.set_pixel(cx - y, cy + x, color);
            self.set_pixel(cx + y, cy - x, color);
            self.set_pixel(cx - y, cy - x, color);
            y += 1;
            if err < 0 {
                err += 2 * y + 1;
            } else {
                x -= 1;
                err += 2 * (y - x) + 1;
            }
        }
    }

    /// Draw 1-bit bitmap text (built-in 6×10 font). Returns advance width.
    pub fn draw_text(&mut self, text: &str, x: i32, y: i32, color: Color, scale: u32) -> i32 {
        let scale = scale.max(1);
        let mut cx = x;
        for ch in text.chars() {
            let glyph = font_glyph(ch);
            for row in 0..FONT_H {
                let bits = glyph[row as usize];
                for col in 0..FONT_W {
                    if bits & (1 << (FONT_W - 1 - col)) != 0 {
                        for sy in 0..scale as i32 {
                            for sx in 0..scale as i32 {
                                self.set_pixel(
                                    cx + col as i32 * scale as i32 + sx,
                                    y + row as i32 * scale as i32 + sy,
                                    color,
                                );
                            }
                        }
                    }
                }
            }
            cx += (FONT_W as u32 * scale + scale) as i32; // character width + 1px gap
        }
        cx - x
    }

    /// Measure text width in pixels for the built-in font.
    pub fn measure_text(text: &str, scale: u32) -> i32 {
        let scale = scale.max(1);
        let chars = text.chars().count() as i32;
        if chars == 0 { return 0; }
        chars * (FONT_W as i32 * scale as i32 + scale as i32)
    }

    /// Convert to BGR (no alpha) for Win32 StretchDIBits (bottom-up row order).
    pub fn to_bgr_bottom_up(&self) -> Vec<u8> {
        let stride = ((self.width * 3 + 3) / 4 * 4) as usize; // 4-byte aligned rows
        let mut out = vec![0u8; stride * self.height as usize];
        for y in 0..self.height {
            let flip_y = self.height - 1 - y;
            let src_row = (y * self.width * 4) as usize;
            let dst_row = flip_y as usize * stride;
            for x in 0..self.width as usize {
                let si = src_row + x * 4;
                let di = dst_row + x * 3;
                out[di]     = self.pixels[si + 2]; // B
                out[di + 1] = self.pixels[si + 1]; // G
                out[di + 2] = self.pixels[si];     // R
            }
        }
        out
    }
}

