#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn scaffold_minimal() {
        let config = ProjectConfig {
            name: "test-app".into(),
            template: ProjectTemplate::Minimal,
            router: false, testing: false, ssr: false,
            ..Default::default()
        };
        let files = scaffold_project(&config);
        assert!(files.iter().any(|f| f.path.contains("main.killer")));
        assert!(files.iter().any(|f| f.path.contains("app.killer")));
        assert!(files.iter().any(|f| f.path.contains("killer.toml")));
        assert!(!files.iter().any(|f| f.path.contains("routes.killer")));
    }

    #[test]
    fn scaffold_with_router() {
        let config = ProjectConfig { router: true, ..Default::default() };
        let files = scaffold_project(&config);
        assert!(files.iter().any(|f| f.path.contains("routes.killer")));
    }

    #[test]
    fn scaffold_fullstack() {
        let config = ProjectConfig {
            template: ProjectTemplate::Fullstack,
            ..Default::default()
        };
        let files = scaffold_project(&config);
        assert!(files.iter().any(|f| f.path.contains("server.killer")));
        assert!(files.iter().any(|f| f.path.contains("api/routes.killer")));
    }

    #[test]
    fn scaffold_dashboard() {
        let config = ProjectConfig {
            template: ProjectTemplate::Dashboard,
            ..Default::default()
        };
        let files = scaffold_project(&config);
        assert!(files.iter().any(|f| f.path.contains("dashboard.killer")));
    }

    #[test]
    fn scaffold_with_ssr() {
        let config = ProjectConfig { ssr: true, ..Default::default() };
        let files = scaffold_project(&config);
        assert!(files.iter().any(|f| f.path.contains("ssr.killer")));
    }

    #[test]
    fn generate_component_basic() {
        let bp = ComponentBlueprint {
            name: "UserCard".into(),
            props: vec![("name".into(), "String".into()), ("age".into(), "Int".into())],
            with_state: true,
            with_lifecycle: true,
            with_test: true,
        };
        let files = generate_component(&bp);
        assert_eq!(files.len(), 2); // component + test
        assert!(files[0].content.contains("component UserCard"));
        assert!(files[0].content.contains("name: String"));
        assert!(files[0].content.contains("on_mount"));
        assert!(files[1].content.contains("UserCard renders"));
    }

    #[test]
    fn parse_cli_init() {
        let cmd = parse_cli(&["init", "my-app"]).unwrap();
        if let CliCommand::Init(config) = cmd {
            assert_eq!(config.name, "my-app");
        } else { panic!("Expected Init"); }
    }

    #[test]
    fn parse_cli_generate() {
        let cmd = parse_cli(&["generate", "component", "Button"]).unwrap();
        if let CliCommand::Generate { kind, name, .. } = cmd {
            assert_eq!(kind, "component");
            assert_eq!(name, "Button");
        } else { panic!("Expected Generate"); }
    }

    #[test]
    fn parse_cli_build_prod() {
        let cmd = parse_cli(&["build", "--prod"]).unwrap();
        if let CliCommand::Build { production } = cmd {
            assert!(production);
        } else { panic!("Expected Build"); }
    }

    #[test]
    fn parse_cli_dev_port() {
        let cmd = parse_cli(&["dev", "--port", "8080"]).unwrap();
        if let CliCommand::Dev { port } = cmd {
            assert_eq!(port, 8080);
        } else { panic!("Expected Dev"); }
    }

    #[test]
    fn parse_cli_unknown() {
        assert!(parse_cli(&["unknown"]).is_err());
    }

    #[test]
    fn parse_cli_empty() {
        assert!(parse_cli(&[]).is_err());
    }

    #[test]
    fn config_has_readme() {
        let files = scaffold_project(&ProjectConfig::default());
        assert!(files.iter().any(|f| f.path.contains("README.md")));
    }
}
