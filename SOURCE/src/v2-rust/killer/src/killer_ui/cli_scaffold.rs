/// A generated file with its path and content.
#[derive(Debug, Clone)]
pub struct GeneratedFile {
    pub path: String,
    pub content: String,
}

/// Generate project scaffold files.
pub fn scaffold_project(config: &ProjectConfig) -> Vec<GeneratedFile> {
    let mut files = Vec::new();
    let name = &config.name;

    // Main entry
    files.push(GeneratedFile {
        path: format!("{}/src/main.killer", name),
        content: generate_main(config),
    });

    // App component
    files.push(GeneratedFile {
        path: format!("{}/src/app.killer", name),
        content: generate_app_component(config),
    });

    // Config
    files.push(GeneratedFile {
        path: format!("{}/killer.toml", name),
        content: generate_config(config),
    });

    // Router (if enabled)
    if config.router {
        files.push(GeneratedFile {
            path: format!("{}/src/routes.killer", name),
            content: generate_routes(config),
        });
    }

    // Test file (if enabled)
    if config.testing {
        files.push(GeneratedFile {
            path: format!("{}/tests/app_test.killer", name),
            content: generate_test(config),
        });
    }

    // Template-specific files
    match config.template {
        ProjectTemplate::Dashboard => {
            files.push(GeneratedFile {
                path: format!("{}/src/pages/dashboard.killer", name),
                content: generate_dashboard_page(),
            });
        }
        ProjectTemplate::Fullstack => {
            files.push(GeneratedFile {
                path: format!("{}/src/api/server.killer", name),
                content: generate_server(),
            });
            files.push(GeneratedFile {
                path: format!("{}/src/api/routes.killer", name),
                content: generate_api_routes(),
            });
        }
        _ => {}
    }

    // Styling
    if config.styling != StylingOption::None {
        files.push(GeneratedFile {
            path: format!("{}/src/styles/global.css", name),
            content: generate_global_css(config),
        });
    }

    // SSR config
    if config.ssr {
        files.push(GeneratedFile {
            path: format!("{}/src/ssr.killer", name),
            content: generate_ssr_config(),
        });
    }

    // README
    files.push(GeneratedFile {
        path: format!("{}/README.md", name),
        content: format!("# {}\n\nGenerated by `killer init`.\n\n## Quick Start\n\n```\nkiller dev\nkiller build\nkiller test\n```\n", name),
    });

    files
}

fn generate_main(config: &ProjectConfig) -> String {
    let mut code = String::from("// Main entry point\n");
    code.push_str(&format!("// Generated by killer init (template: {:?})\n\n", config.template));
    code.push_str("import \"./app\"\n\n");
    if config.router {
        code.push_str("import \"./routes\"\n\n");
    }
    code.push_str("kfn main() {\n");
    code.push_str("    let app = App()\n");
    code.push_str("    render(app)\n");
    code.push_str("}\n");
    code
}

fn generate_app_component(config: &ProjectConfig) -> String {
    let mut code = String::from("// Root application component\n\n");
    code.push_str("component App {\n");
    code.push_str("    state {\n");
    code.push_str(&format!("        title: \"{}\"\n", config.name));
    code.push_str("        count: 0\n");
    code.push_str("    }\n\n");
    code.push_str("    render {\n");
    code.push_str("        <Column>\n");
    code.push_str("            <Label text={state.title} />\n");
    code.push_str("            <Button label=\"Click me\" @click={state.count = state.count + 1} />\n");
    code.push_str("            <Label text={\"Count: \" + state.count} />\n");
    code.push_str("        </Column>\n");
    code.push_str("    }\n");
    code.push_str("}\n");
    code
}

fn generate_config(config: &ProjectConfig) -> String {
    let mut toml = String::from("[project]\n");
    toml.push_str(&format!("name = \"{}\"\n", config.name));
    toml.push_str("version = \"0.1.0\"\n\n");
    toml.push_str("[build]\n");
    toml.push_str("target = \"web\"\n");
    toml.push_str("minify = true\n");
    toml.push_str("tree_shake = true\n\n");
    if !config.features.is_empty() {
        toml.push_str("[features]\n");
        for f in &config.features {
            toml.push_str(&format!("{} = true\n", f));
        }
    }
    toml
}

fn generate_routes(_config: &ProjectConfig) -> String {
    let mut code = String::from("// Application routes\n\n");
    code.push_str("routes {\n");
    code.push_str("    \"/\" => HomePage\n");
    code.push_str("    \"/about\" => AboutPage\n");
    code.push_str("    \"/settings\" => SettingsPage\n");
    code.push_str("    \"*\" => NotFoundPage\n");
    code.push_str("}\n");
    code
}

fn generate_test(_config: &ProjectConfig) -> String {
    let mut code = String::from("// App tests\n\n");
    code.push_str("test \"app renders\" {\n");
    code.push_str("    let host = TestHost()\n");
    code.push_str("    host.render(App())\n");
    code.push_str("    assert(host.query_by_text(\"Click me\") != null)\n");
    code.push_str("}\n\n");
    code.push_str("test \"counter increments\" {\n");
    code.push_str("    let host = TestHost()\n");
    code.push_str("    host.render(App())\n");
    code.push_str("    host.fire_click(\"btn\")\n");
    code.push_str("    assert(host.query_by_text(\"Count: 1\") != null)\n");
    code.push_str("}\n");
    code
}

fn generate_dashboard_page() -> String {
    "// Dashboard page\n\ncomponent DashboardPage {\n    render {\n        <Dashboard title=\"Admin\">\n            <StatCard title=\"Users\" value=\"1,234\" trend=\"+12%\" />\n            <StatCard title=\"Revenue\" value=\"$42K\" trend=\"+8%\" />\n            <DataGrid columns={[\"Name\", \"Email\", \"Role\"]} />\n        </Dashboard>\n    }\n}\n".into()
}

fn generate_server() -> String {
    "// API server\n\nkfn start_server(port) {\n    let server = HttpServer(port)\n    server.use(cors())\n    server.use(json_parser())\n    import \"./routes\"\n    server.listen()\n}\n".into()
}

fn generate_api_routes() -> String {
    "// API routes\n\napi {\n    GET  \"/api/users\"     => get_users\n    POST \"/api/users\"     => create_user\n    GET  \"/api/users/:id\" => get_user\n}\n".into()
}

fn generate_global_css(config: &ProjectConfig) -> String {
    match config.styling {
        StylingOption::MaterialTheme => "/* Material Design tokens */\n:root {\n    --primary: #1976d2;\n    --secondary: #9c27b0;\n    --error: #d32f2f;\n    --background: #ffffff;\n    --surface: #f5f5f5;\n    --spacing: 8px;\n    --radius: 4px;\n}\n\n* { box-sizing: border-box; margin: 0; padding: 0; }\nbody { font-family: 'Roboto', sans-serif; }\n".into(),
        _ => "/* Global styles */\n:root {\n    --primary: #0070f3;\n    --background: #ffffff;\n}\n\n* { box-sizing: border-box; margin: 0; padding: 0; }\n".into(),
    }
}

fn generate_ssr_config() -> String {
    "// SSR configuration\n\nssr {\n    mode: \"streaming\"\n    hydrate: true\n    routes: [\"/\", \"/about\"]\n}\n".into()
}

