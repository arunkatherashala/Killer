/// Blueprint for generating a component.
#[derive(Debug, Clone)]
pub struct ComponentBlueprint {
    pub name: String,
    pub props: Vec<(String, String)>, // (name, type)
    pub with_state: bool,
    pub with_lifecycle: bool,
    pub with_test: bool,
}

/// Generate component boilerplate files.
pub fn generate_component(bp: &ComponentBlueprint) -> Vec<GeneratedFile> {
    let mut files = Vec::new();
    let name_lower = bp.name.to_lowercase();

    let mut code = format!("// {} component\n\n", bp.name);
    code.push_str(&format!("component {} {{\n", bp.name));

    if !bp.props.is_empty() {
        code.push_str("    props {\n");
        for (name, typ) in &bp.props {
            code.push_str(&format!("        {}: {}\n", name, typ));
        }
        code.push_str("    }\n\n");
    }

    if bp.with_state {
        code.push_str("    state {\n        loading: false\n    }\n\n");
    }

    if bp.with_lifecycle {
        code.push_str("    on_mount {\n        // Initialize\n    }\n\n");
        code.push_str("    on_unmount {\n        // Cleanup\n    }\n\n");
    }

    code.push_str("    render {\n");
    code.push_str(&format!("        <Column>\n            <Label text=\"{}\" />\n        </Column>\n", bp.name));
    code.push_str("    }\n");
    code.push_str("}\n");

    files.push(GeneratedFile {
        path: format!("src/components/{}.killer", name_lower),
        content: code,
    });

    if bp.with_test {
        let mut test_code = format!("// {} tests\n\n", bp.name);
        test_code.push_str(&format!("test \"{} renders\" {{\n", bp.name));
        test_code.push_str("    let host = TestHost()\n");
        test_code.push_str(&format!("    host.render({}())\n", bp.name));
        test_code.push_str(&format!("    assert(host.query_by_text(\"{}\") != null)\n", bp.name));
        test_code.push_str("}\n");
        files.push(GeneratedFile {
            path: format!("tests/components/{}_test.killer", name_lower),
            content: test_code,
        });
    }

    files
}

/// CLI command representation.
#[derive(Debug, Clone)]
pub enum CliCommand {
    Init(ProjectConfig),
    Generate { kind: String, name: String, options: HashMap<String, String> },
    Build { production: bool },
    Dev { port: u16 },
    Test { filter: Option<String> },
    Lint,
    Format,
}

/// Parse CLI args into a command.
pub fn parse_cli(args: &[&str]) -> Result<CliCommand, String> {
    if args.is_empty() {
        return Err("No command specified. Usage: killer <init|generate|build|dev|test|lint|format>".into());
    }
    match args[0] {
        "init" => {
            let mut config = ProjectConfig::default();
            if args.len() > 1 { config.name = args[1].to_string(); }
            Ok(CliCommand::Init(config))
        }
        "generate" | "g" => {
            if args.len() < 3 { return Err("Usage: killer generate <component|page|service> <name>".into()); }
            Ok(CliCommand::Generate {
                kind: args[1].into(),
                name: args[2].into(),
                options: HashMap::new(),
            })
        }
        "build" => {
            let production = args.iter().any(|a| *a == "--prod" || *a == "--production");
            Ok(CliCommand::Build { production })
        }
        "dev" => {
            let port = args.iter().position(|a| *a == "--port")
                .and_then(|i| args.get(i + 1))
                .and_then(|p| p.parse::<u16>().ok())
                .unwrap_or(3000);
            Ok(CliCommand::Dev { port })
        }
        "test" => {
            let filter = if args.len() > 1 { Some(args[1].to_string()) } else { None };
            Ok(CliCommand::Test { filter })
        }
        "lint" => Ok(CliCommand::Lint),
        "format" | "fmt" => Ok(CliCommand::Format),
        cmd => Err(format!("Unknown command: '{}'. Available: init, generate, build, dev, test, lint, format", cmd)),
    }
}

