//! **CLI Scaffold** — Project scaffolding and code generation.
//!
//! `killer init`, `killer generate component`, `killer build`, etc.
//! Generates project templates, component boilerplate, route configs, test files.
//! Equivalent to Angular CLI / Create React App / Vite CLI.

use std::collections::HashMap;

// ══════════════════════════════════════════════════════════════════════════════
// Project template
// ══════════════════════════════════════════════════════════════════════════════

/// Template types for project initialization.
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum ProjectTemplate {
    Minimal,
    App,
    Dashboard,
    Fullstack,
    Library,
}

/// Project configuration.
#[derive(Debug, Clone)]
pub struct ProjectConfig {
    pub name: String,
    pub template: ProjectTemplate,
    pub features: Vec<String>,
    pub styling: StylingOption,
    pub testing: bool,
    pub ssr: bool,
    pub router: bool,
}

#[derive(Debug, Clone, Copy, PartialEq)]
pub enum StylingOption {
    None,
    Css,
    Tailwind,
    MaterialTheme,
}

impl Default for ProjectConfig {
    fn default() -> Self {
        ProjectConfig {
            name: "my-killer-app".into(),
            template: ProjectTemplate::App,
            features: Vec::new(),
            styling: StylingOption::Css,
            testing: true,
            ssr: false,
            router: true,
        }
    }
}

